#!/usr/bin/env python3
"""Turn experiments/results/*.json into LaTeX tables.

This exists so no number is ever typed into a .tex file by hand. The paper
reads tables/*.tex; those files are generated, and overwriting them is the
only way a result changes.

Each result file is expected to look like:

    {"run_id": "...", "commit": "...", "seed": 0,
     "dataset": "...", "metrics": {"accuracy": 0.81, "f1": 0.79}}

Usage:
    python analysis/make_tables.py
"""

from __future__ import annotations

import glob
import json
import os
import sys

RESULTS_DIR = "experiments/results"
OUT_PATH = "paper/tables/main_results.tex"


def load_runs() -> list[dict]:
    runs = []
    for path in sorted(glob.glob(os.path.join(RESULTS_DIR, "*.json"))):
        with open(path) as fh:
            try:
                runs.append(json.load(fh))
            except ValueError as exc:
                print(f"make_tables: {path} is not valid JSON ({exc}). Skipped.")
    return runs


def main() -> int:
    runs = load_runs()
    if not runs:
        print(f"make_tables: no result files in {RESULTS_DIR}/. Nothing to write.")
        return 0

    metric_names: list[str] = []
    for run in runs:
        for name in (run.get("metrics") or {}):
            if name not in metric_names:
                metric_names.append(name)

    header = " & ".join(["Run", "Dataset"] + [n.replace("_", " ") for n in metric_names])
    lines = [
        "% Generated by analysis/make_tables.py. Do not edit by hand.",
        "% Regenerate with: make tables",
        "\\begin{table}[t]",
        "  \\centering",
        "  \\caption{Main results. Write the caption here, in make\\_tables.py.}",
        "  \\label{tab:main-results}",
        "  \\begin{tabular}{ll" + "r" * len(metric_names) + "}",
        "    \\toprule",
        f"    {header} \\\\",
        "    \\midrule",
    ]
    for run in runs:
        metrics = run.get("metrics") or {}
        cells = [str(run.get("run_id", "?")).replace("_", "\\_"),
                 str(run.get("dataset", "-"))]
        for name in metric_names:
            value = metrics.get(name)
            cells.append("-" if value is None
                         else (f"{value:.3f}" if isinstance(value, float) else str(value)))
        lines.append("    " + " & ".join(cells) + " \\\\")
    lines += [
        "    \\bottomrule",
        "  \\end{tabular}",
        "\\end{table}",
    ]

    os.makedirs(os.path.dirname(OUT_PATH), exist_ok=True)
    with open(OUT_PATH, "w") as fh:
        fh.write("\n".join(lines) + "\n")

    commits = {run.get("commit", "?") for run in runs}
    print(f"make_tables: wrote {OUT_PATH} from {len(runs)} run(s); "
          f"commit(s): {', '.join(sorted(commits))}")
    print(f"make_tables: include it with \\input{{tables/main_results}}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
